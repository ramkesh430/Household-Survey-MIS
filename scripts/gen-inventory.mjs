// Generates docs/01-question-inventory.md from shared/questionnaire.js (single source of truth).
import fs from 'node:fs';
import { questions, sections } from '../shared/questionnaire.js';
import { toNepaliDigits as np } from '../shared/engine.js';

const TYPE = { text: 'पाठ', number: 'संख्या', date: 'मिति (वि.सं.)', single: 'एक उत्तर', multi: 'बहु उत्तर', grid: 'तालिका (निश्चित पंक्ति)',
  repeat: 'तालिका (थप्न मिल्ने पंक्ति)', groupedRepeat: 'समूहगत तालिका', signature: 'सही' };
const L = [];
L.push('# प्रश्न सूची (Page-by-page question inventory)', '');
L.push('> Generated by `node scripts/gen-inventory.mjs` from `shared/questionnaire.js` — do not edit by hand.', '');
L.push(`Numbered questions: **${questions.filter((q) => q.no).length}** · plus the page-1 header block and the page-22 verification block.`, '');
let page = 0;
for (const q of questions) {
  if (q.page !== page) { page = q.page; L.push(`## PDF पृष्ठ ${np(page)} (page ${page})`, ''); }
  const sec = sections.find((s) => s.id === q.section);
  L.push(`### ${q.no ? `${q.no}. ` : ''}${q.title}  \`${q.id}\``);
  L.push(`*खण्ड:* ${sec.title}${q.sensitive ? ' · **संवेदनशील**' : ''}${q.showIf ? ` · *देखाउने सर्त:* ${q.showIf.q}.${q.showIf.field} = ${q.showIf.eq}` : ''}`);
  if (q.note) L.push(`*नोट:* ${q.note}`);
  L.push('');
  for (const f of q.fields) {
    const flags = [f.required && 'आवश्यक', f.reviewOnly && 'सुपरभाइजर मात्र', f.fromHousehold && 'घरधुरी दर्ताबाट स्वतः', f.computedFrom && 'स्वतः गणना',
      f.showIf && `सर्त: ${f.showIf.field} ${f.showIf.eq ? `= ${f.showIf.eq}` : `∈ ${(f.showIf.includesAny || f.showIf.in).join(', ')}`}`].filter(Boolean);
    L.push(`- **${f.label || '(उत्तर)'}** — ${TYPE[f.type]}${flags.length ? ` _(${flags.join('; ')})_` : ''}`);
    if (f.options) L.push(`  - विकल्प: ${f.options.map((o) => `${o.code}) ${o.label}${o.value !== o.code ? ` [value: ${o.value}]` : ''}${o.specify ? ' ✎' : ''}${o.exclusive ? ' ⊘' : ''}`).join(' · ')}`);
    if (f.type === 'grid') {
      L.push(`  - पंक्ति: ${f.rows.map((r) => r.label + (r.specify ? ' ✎' : '')).join(' · ')}${f.totalRow ? ' · **जम्मा (स्वतः)**' : ''}`);
      L.push(`  - स्तम्भ: ${f.cols.map((c) => `${c.group ? `${c.group} › ` : ''}${c.label}${c.sumOf ? ' (स्वतः)' : ''}`).join(' · ')}`);
      if (f.rowChoice) L.push('  - प्रत्येक पंक्तिमा एउटा मात्र ✓');
      (f.rowRules || []).forEach((r) => L.push(`  - नियम: ${r.message}${r.warn ? ' (चेतावनी)' : ''}`));
    }
    if (f.type === 'repeat' || f.type === 'groupedRepeat') {
      L.push(`  - स्तम्भ: ${f.columns.map((c) => `${c.group ? `${c.group} › ` : ''}${c.label}${c.options ? ` [${c.options.map((o) => o.label).join('/')}]` : ''}`).join(' · ')}`);
      if (f.groups) L.push(`  - समूह: ${f.groups.map((g) => g.label).join(' · ')}`);
    }
  }
  L.push('');
}
L.push('---', '', 'Legend: ✎ = "अन्य/खुलाउने" free-text required when chosen · ⊘ = exclusive option (cannot combine) · [value] = internal storage key where the PDF repeats a code.');
fs.writeFileSync(new URL('../docs/01-question-inventory.md', import.meta.url), L.join('\n'));
console.log(`wrote ${L.length} lines`);
